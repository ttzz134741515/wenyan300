const STORY_SCENES = [
  "清晨，书生子安入城应试",
  "午后，他随驿使经过县署",
  "傍晚，众人在江亭避雨",
  "夜里，先生点灯复盘今日见闻",
  "次日，他把这段经历讲给同窗",
];

function makeStory(word, meanings) {
  return meanings.map((meaning, index) => {
    const scene = STORY_SCENES[index % STORY_SCENES.length];
    return `${scene}，眼前的“${word}”正作“${meaning}”解`;
  }).join("；") + "。一字随情境转义，故事也由此串成。";
}

function makeTranslation(word, meanings) {
  return `故事依次串联“${word}”的${meanings.length}个常见义项：${meanings.join("、")}。记忆时先回想时间顺序，再还原每一处含义。`;
}

window.WORDS = RAW_WORDS.split("\n").map((line, index) => {
  const [word, rawMeanings] = line.split("|");
  const meanings = rawMeanings.split("/");
  return {
    id: index + 1,
    word,
    meanings,
    story: makeStory(word, meanings),
    translation: makeTranslation(word, meanings),
  };
});

if (window.REFERENCE_STORIES) {
  window.WORDS = window.WORDS.map((item) => {
    const reference = window.REFERENCE_STORIES[item.word];
    return reference ? { ...item, story: reference.story, translation: reference.translation } : item;
  });
}
